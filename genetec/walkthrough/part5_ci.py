"""Part 5: dependencies, versions, CI."""
from bookkit import M

WF = "../.github/workflows/genetec.yml"
DB = "../.github/dependabot.yml"


def write(b):
    b.PART("Part 5", "Keeping it working",
           "The same three ideas as the robot arm's Appendix C, applied to a .NET solution: dependencies pinned by lock "
           "files, versions that mean something, and CI that builds and tests everything on every push, on Windows for "
           "the WPF apps and on Linux for SQL Server. Plus the real problems those checks caught while the snacks were built.")

    b.H1("5.1 One build for four snacks")
    b.whole("Directory.Build.props", "xml")
    b.P("MSBuild imports " + M("Directory.Build.props") + " into every project below it, before the project's own "
        "settings. One place sets nullable reference types, the language version, lock files and the version number "
        "for all fourteen projects; a project can still override any of them.")
    b.whole("global.json", "json")
    b.notes("global.json", [
        ("\"version\": \"10.0.100\"", "The minimum SDK..."),
        ("\"rollForward\": \"latestFeature\"", "...and any later feature band of .NET 10 (10.0.2xx, 10.0.3xx) is "
         "accepted, but not .NET 11. Everyone, including CI, builds with a .NET 10 SDK."),
        ("\"runner\": \"Microsoft.Testing.Platform\"", "xUnit v3's current releases run on Microsoft.Testing.Platform. "
         "On the .NET 10 SDK, " + M("dotnet test") + " has to be told to use it, or it fails with \"Testing with VSTest "
         "target is no longer supported\". That's exactly how the first CI run failed."),
    ])

    b.H1("5.2 Lock files")
    b.P("Every project has a " + M("packages.lock.json") + " beside it, written because " +
        M("RestorePackagesWithLockFile") + " is on. It records the exact version and content hash of every package "
        "the project uses, direct and transitive, per target framework (Snack 2's core has two sections, " + M("net48") +
        " and " + M("net10.0") + "). It's NuGet's " + M("package-lock.json") + ".")
    b.P(M("dotnet restore --locked-mode") + " installs exactly what the lock file records and fails if the project "
        "asks for something else, like " + M("npm ci") + ". But it has a gap: a project with <i>no</i> lock file "
        "restores happily. CI closes it with a check of its own:")
    b.code(WF, "- name: Every project has a committed lock file", "yaml", end="exit $missing")
    b.P("This was added after the first Genetec run went green with no lock files at all: " + M("--locked-mode") +
        " had nothing to enforce. A check that can't fail isn't a check.")
    b.H2("Exact versions in the project files")
    b.P("The lock files were generated by restoring with floating versions (" + M("Version=\"*\"") + ", \"the newest\"), "
        "and then every project file was pinned to the exact version the lock resolved, with the lock files updated to "
        "match. A project file should say what's actually used; a " + M("*") + " in it means the next restore without "
        "a lock file could pull something new.")

    b.H1("5.3 A vulnerable transitive dependency")
    b.P("The first restore of Snack 2 printed warnings " + M("NU1902") + " and " + M("NU1903") + ": "
        + M("System.Security.Cryptography.Pkcs") + " 8.0.1 and 9.0.18 have known moderate and high severity "
        "vulnerabilities. Snack 2 never mentions Pkcs. It comes in through " + M("Microsoft.Data.SqlClient") +
        ", which depends on it: a <b>transitive dependency</b>.")
    b.P("NuGet resolves each package to the lowest version that satisfies every request (unlike npm, which takes "
        "the newest allowed). So adding a direct reference to a patched version raises the floor, and NuGet picks it "
        "for the whole graph. That's the override in " + M("AccessLog.Core.csproj") + ". The same thing happened in "
        "Full Stack's dotnet-sqlserver, where EF Core 10.0.0 pulled in the vulnerable Pkcs; there, the EF Core 10.0.15 "
        "patch release depended on a fixed version, so a patch bump was enough.")
    b.code(WF, "- name: Vulnerable packages", "yaml", end="! grep -q -E")
    b.P("Now CI fails if a high or critical advisory appears in anything the solution uses, including packages "
        "nobody chose directly.")

    b.H1("5.4 Semantic Versioning for a .NET solution")
    b.P("The version lives in " + M("Directory.Build.props") + " and is stamped into every assembly. "
        + M("CHANGELOG.md") + " defines what counts as breaking for each snack, because \"public API\" means "
        "different things in each:")
    b.T([["Snack", "Its contract", "A breaking change, for example"],
         ["1. Camera Monitor", "The app itself", "requiring a newer Windows or .NET"],
         ["2. Access Event Log", "The database schema; IAccessEventRepository (Snack 4 uses it)", "a column existing databases don't have; a renamed method"],
         ["3. Plugin framework", "SolutionFramework.Abstractions", "a new member on ISolutionModule: every module stops loading"],
         ["4. Web Dashboard", "The HTTP API", "a renamed route, parameter or JSON field"]], [1.6, 2.6, 2.55])
    b.P("Snack 3 is the clearest case. The contract assembly is a public API for every module ever written. Adding a "
        "method to " + M("ISolutionModule") + " looks like a small, additive change, but every existing module "
        "fails to load. That's a major version. A default interface method, or a second optional interface, keeps it "
        "minor.")

    b.H1("5.5 The workflow")
    b.code(WF, "name: genetec", "yaml", end="cancel-in-progress: true", doc=False)
    b.P("No path filters: every push to any branch and every pull request runs the checks, so branch protection's "
        "required checks always report.")
    b.code(WF, "  windows:", "yaml", end="- run: dotnet test --solution Genetec.slnx --no-build -c Release", doc=False)
    b.notes(WF, [
        ("runs-on: windows-latest", "The WPF apps only build on Windows. (Snack 1's sets " + M("EnableWindowsTargeting") +
         " and could compile on Linux; the .NET Framework one can't.)"),
        ("global-json-file: genetec/global.json", "CI installs the SDK " + M("global.json") + " asks for, so CI and "
         "your machine agree."),
        ("dotnet build Genetec.slnx --no-restore -c Release -warnaserror", "Warnings fail the build. This caught "
         "xUnit's analyzer rule " + M("xUnit1051") + " (pass the test's cancellation token to async calls) and the "
         "compiler's CS9124 (a constructor parameter captured twice) before they reached " + M("main") + "."),
    ])
    b.code(WF, "  sqlserver:", "yaml", end="- run: dotnet test --project snack2-access-event-log/tests/AccessLog.Tests --no-build -c Release", doc=False)
    b.P("Windows runners can't run Linux containers, so SQL Server's tests run on Linux. GitHub starts "
        + M("mcr.microsoft.com/mssql/server") + " as a <b>service container</b> beside the job, waits for its health "
        "check, and the tests reach it on " + M("localhost:1433") + ". On the Windows job the same tests are "
        "reported as skipped, which is also how they behave on a laptop without SQL Server.")
    b.H2("What the SQL Server job caught")
    b.B(["<b>EXEC can't call a function.</b> " + M("EXEC(N'CREATE DATABASE ' + QUOTENAME(@db))") + " is a syntax "
         "error; the statement must be built in a variable first. Every database test failed until it was fixed.",
         "<b>Error 547 means two things.</b> SQL Server reports foreign-key and CHECK violations with the same number. "
         "The repository turned both into \"unknown device\". The contract test for the CHECK rule, run on both stores, "
         "showed the in-memory store and SQL Server disagreeing.",
         "<b>A dozen rows don't need an index.</b> The query-plan test first ran on a nearly empty table, where reading "
         "everything is the cheapest plan, so SQL Server ignored the index. The test now inserts 20,000 rows first."])
    b.P("None of these would show up with the in-memory store alone. That's the argument for running the contract "
        "against the real database in CI.")

    b.H1("5.6 Dependabot")
    a = b.ln(DB, "  # ---- genetec ----")
    e = b.ln(DB, "dependency-name: \"@types/node\"", a) + 1  # through the npm entry's last rule
    b.lines(DB, a, e, "yaml")
    b.P("NuGet updates for every Genetec project, with xUnit's packages grouped (they release together), and npm "
        "updates for Snack 4's page, with Vite and its React plugin grouped (each new major needs the other). Each "
        "update arrives as a pull request, and the workflow above tests it before anyone merges.")
    b.P("The " + M("ignore") + " rules skip major versions of Microsoft's " + M("System.*") + " and "
        + M("Microsoft.*") + " packages. Those follow the .NET version: 10.x goes with " + M("net10.0") + ". Dependabot's "
        "first run offered " + M("System.Security.Cryptography.Pkcs") + " 11.0.0 for Snack 2, the package from 5.3. "
        "It updated one project's lock file but not the ones that reference it, so " + M("--locked-mode") + " failed "
        "everywhere else, which is the lock check doing its job. 10.0.x already has the fix, so the pull request was "
        "closed, and moving to .NET 11 stays a deliberate change for the whole solution.")

    b.H1("5.7 Running it all")
    b.T([["Snack", "Run", "Test"],
         ["1", M("dotnet run --project snack1-camera-status-monitor/src/CameraMonitor.App"), M("dotnet test --project snack1-.../tests/CameraMonitor.Tests")],
         ["2", M("docker compose up -d") + " in snack2, then " + M("dotnet run --project src/AccessLog.App"), "set " + M("TEST_SQLSERVER") + " to include SQL Server"],
         ["3", M("dotnet run --project src/SolutionFramework.Host") + " (after a build)", M("dotnet test --project tests/SolutionFramework.Tests")],
         ["4", M("dotnet run --project api/Dashboard.Api") + "; " + M("npm run dev") + " in web/", M("dotnet test") + "; " + M("npm test") + " in web/"],
         ["All", M("dotnet build") + " in genetec/", M("dotnet test") + " in genetec/"]], [0.5, 3.4, 2.85])

    b.H1("5.8 Interview questions")
    b.QA("What does packages.lock.json add if the .csproj already has exact versions?",
         "The transitive graph. The project file pins only direct dependencies; the lock records every package below them "
         "and its content hash, so restore can't silently pick a different transitive version or a tampered package.")
    b.QA("A package you never referenced has a vulnerability. How do you fix it?",
         "Find who brings it in (" + M("dotnet list package --include-transitive") + "), then either update the direct "
         "dependency to a release that depends on a fixed version, or reference the fixed version directly, which NuGet's "
         "lowest-applicable-version rule makes win.")
    b.QA("Why does the solution build with -warnaserror in CI but not locally?",
         "Locally, a warning is information while you work; on the way into main, it's a defect. Failing CI on warnings "
         "stops them piling up until nobody reads them.")
    b.QA("Why test against a real SQL Server when there's an in-memory repository?",
         "The in-memory store tests the logic above the database; only the real one tests the SQL, the constraints and "
         "the indexes. Three real bugs in this snack only showed up there.")
